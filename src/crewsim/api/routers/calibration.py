"""Phase-0 statistical calibration jobs.

What was removed here, and why it mattered: this router used to attach a
`final_log_likelihood` of -1204.45 and a twenty-point "convergence" curve to
every completed job. Neither came from the fit. The curve was generated by a
fixed arithmetic recurrence that always produces a healthy-looking rise-and-
plateau, and the UI rendered it under the heading "Log-Likelihood Convergence"
with help text telling the reader that shape means the optimiser found the best
parameters. `/compare` returned `random.uniform()` values, so the same two jobs
compared differently on every refresh -- in a project whose spine is CRN
streams, ledger hashing and reproducible runs.

The pipeline does not report per-iteration history or a final likelihood, so
this router no longer claims either. It reports what `run_pipeline` actually
returns.
"""

from __future__ import annotations

import uuid
import warnings
from datetime import datetime
from pathlib import Path
from typing import Any

from fastapi import APIRouter, BackgroundTasks, Depends, HTTPException
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, ConfigDict
from sqlalchemy.orm import Session

from crewsim.api.db import Job, SessionLocal, get_db, get_job_or_404, record_job_failure
from crewsim.api.runlog import RunLog
from crewsim.api.streaming import stream_job

router = APIRouter(prefix="", tags=["calibration"])

_PERCENT = 100

# The fits `run_pipeline` performs, keyed by the id the UI offers. Selecting a
# subset is not supported: the pipeline runs as a unit, so a request naming
# anything outside this set is rejected rather than silently ignored.
SUPPORTED_MODELS = frozenset(
    {
        "transition_matrix",
        "intensity_multipliers",
        "nhpp_covariates",
        "mixture_dist",
        "lognormal_dist",
    }
)


class CalibrationJobCreate(BaseModel):
    name: str
    season: str | None = None
    models_to_fit: list[str]


class CalibrationJobResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    type: str
    status: str
    progress: int
    created_at: datetime
    updated_at: datetime
    error_message: str | None = None


def run_calibration_job(job_id: str, season: str | None = None) -> None:
    db = SessionLocal()
    try:
        job = db.query(Job).filter(Job.id == job_id).first()
        if not job:
            return

        job.status = "running"
        db.commit()

        from crewsim import config
        from crewsim.calibration import pipeline

        def flush(entries: list[dict[str, Any]]) -> None:
            # Reassign, don't mutate: SQLAlchemy's JSON column tracks identity,
            # so an in-place append would not register as a change.
            job.log = entries
            db.commit()

        runlog = RunLog(total_steps=len(pipeline.PHASES), flush=flush)

        cfg = config.load()
        resolved_season = season or cfg.scope.season

        def on_step(index: int, total: int, label: str) -> None:
            """Called by run_pipeline as each phase begins.

            The three fitters are single long calls with no internal progress,
            so this reports which phase is in flight and closes the previous
            one -- honest granularity rather than a bar interpolating through
            work it cannot see.
            """
            if index > 1:
                runlog.done()
            runlog.start(label, detail=pipeline.PHASES[index - 1][1])
            # Progress is measured on phases COMPLETED, so the bar does not
            # show 25% before the first fitter has produced anything.
            job.progress = int((index - 1) / total * _PERCENT)
            db.commit()

        # Capture fit-quality warnings instead of letting them go to stderr and
        # vanish. statsmodels raises ConvergenceWarning ("Maximum Likelihood
        # optimization failed to converge") on some seasons, which is precisely
        # the kind of thing a planner reading these parameters must be told --
        # a silent non-converged fit looks identical to a good one downstream.
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            store = pipeline.run_pipeline(
                cfg, season=resolved_season, window_name="fitting", on_step=on_step
            )
        runlog.done()

        # De-duplicated: a fitter can emit the same warning many times.
        for message in dict.fromkeys(f"{w.category.__name__}: {w.message}" for w in caught):
            runlog.note(message, level="warning")

        # What the data could not support, so a planner reads it beside the fit.
        found_limitations = (store.get("diagnostics") or {}).get("limitations", [])
        for item in found_limitations:
            if item.get("severity") in ("HIGH", "MEDIUM"):
                runlog.note(f"Limitation: {item.get('title')} -- {item.get('detail')}", level="warning")

        nhpp = store.get("sick_call_nhpp", {})
        mixture = store.get("flight_delay_mixture", {})
        components = mixture.get("components", [])
        regime_hmm = store.get("regime_hmm", {})
        hmm_fit = regime_hmm.get("fit") or {}
        settings = cfg.calibration.regime_hmm

        job.results = {
            "season": resolved_season,
            "limitations": found_limitations,
            "fitted": {
                "transition_matrix": store.get("markov_transition_matrix_P", []),
                "regime_pi0": store.get("markov_steady_state_pi0", {}),
                "intensity_multipliers": store.get("intensity_multipliers", {}),
                # F-42: the regime is a hidden Markov model -- per-state
                # emissions, BIC model selection and the holdout score.
                "regime_hmm": regime_hmm,
                "nhpp_coefficients": nhpp.get("coefficients", {}),
                "nhpp_dispersion": nhpp.get("dispersion"),
                "nhpp_category_levels": nhpp.get("category_levels", {}),
                "base_delay_probability": mixture.get("base_delay_probability"),
                "mixture_components": components,
                "duration_lognorm": {
                    "shape": nhpp.get("duration_lognorm_shape"),
                    "scale": nhpp.get("duration_lognorm_scale"),
                },
            },
            # The real thresholds/settings the pipeline was actually run
            # with, for the UI's "how was this calibrated" explanation --
            # not restated from memory, read from the same cfg the fit used.
            "calibration_settings": {
                "regime_hmm": {
                    "n_restarts": settings.n_restarts,
                    "max_iter": settings.max_iter,
                    "tol": settings.tol,
                    "transition_pseudocount": settings.transition_pseudocount,
                    "delay_threshold_minutes": settings.delay_threshold_minutes,
                    "sick_call_exposure": settings.sick_call_exposure,
                },
                "delay_gmm_components": cfg.calibration.delay_gmm_components,
            },
            # F-42: the regime HMM is a real likelihood fit, so its goodness
            # of fit is reported -- read from the store, never invented. The
            # NB GLM and the delay mixture still report no likelihood here.
            "goodness_of_fit": (
                {
                    "model": "regime hidden Markov model",
                    "log_likelihood": hmm_fit.get("log_likelihood"),
                    "bic": hmm_fit.get("bic"),
                    "n_days": hmm_fit.get("n_days"),
                    "converged": hmm_fit.get("converged"),
                    "restarts_reaching_best": hmm_fit.get("restarts_reaching_best"),
                    "restarts": hmm_fit.get("restarts"),
                    "holdout": regime_hmm.get("holdout"),
                    "bic_preferred_n_states": (regime_hmm.get("model_selection") or {}).get(
                        "bic_preferred_n_states"
                    ),
                }
                if hmm_fit else None
            ),
            "goodness_of_fit_note": (
                "Reported for the regime hidden Markov model only (log-likelihood, BIC, "
                "restart agreement, holdout log-likelihood per day vs a one-state model). "
                "The sick-call GLM and the delay mixture do not report one here."
            ),
        }
        # Filename only. The absolute path leaks the developer's home directory
        # into a log a planner reads, and the containing directory is already
        # configuration (paths.params_dir) rather than news.
        saved_path = store.get("_saved_path")
        saved_name = Path(saved_path).name if saved_path else "no file written"
        runlog.note(
            f"Wrote {store.get('content_hash', 'no hash')} -> {saved_name}",
            artifact=saved_name if saved_path else None,
        )
        job.diagnostics = None
        job.progress = _PERCENT
        job.status = "completed"
        db.commit()
    except Exception as exc:  # noqa: BLE001 - surfaced to the caller via the job row
        record_job_failure(
            db, job_id, exc, total_steps=len(pipeline.PHASES),
            progress_done=None, progress_total=None, artifact=None,
        )
    finally:
        db.close()


@router.post("/jobs", response_model=CalibrationJobResponse)
def launch_calibration(
    job_in: CalibrationJobCreate,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
) -> Job:
    # Reject what cannot be honoured. This endpoint used to accept a dataset and
    # a model selection and then discard both, always fitting everything.
    unknown = sorted(set(job_in.models_to_fit) - SUPPORTED_MODELS)
    if unknown:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported model(s): {', '.join(unknown)}",
        )
    if set(job_in.models_to_fit) != SUPPORTED_MODELS:
        raise HTTPException(
            status_code=400,
            detail=(
                "The calibration pipeline runs as a unit; fitting a subset is not "
                "supported. Request all of: " + ", ".join(sorted(SUPPORTED_MODELS))
            ),
        )

    # Resolved here, not in the worker: `season=None` means "the configured
    # default", and the caller should see which season that actually was.
    from crewsim import config as cfgmod

    resolved_season = job_in.season or cfgmod.load().scope.season

    job = Job(
        id=str(uuid.uuid4()),
        type="calibration",
        status="queued",
        progress=0,
        season=resolved_season,
    )
    db.add(job)
    db.commit()
    db.refresh(job)

    background_tasks.add_task(run_calibration_job, job.id, resolved_season)
    return job


@router.get("/{job_id}/results")
def get_calibration_results(job_id: str, db: Session = Depends(get_db)) -> dict[str, Any]:
    job = get_job_or_404(job_id, db)
    return {"job_id": job_id, "status": job.status, **(job.results or {})}


@router.get("/{job_id}/logs")
def get_calibration_logs(job_id: str, db: Session = Depends(get_db)) -> dict[str, Any]:
    """The structured execution log, same shape the processing router serves.

    The previous version returned a fixed seven-line script ("Fit converged.",
    "params_vX.json generated.") printed verbatim for every job, including
    failed ones.
    """
    job = get_job_or_404(job_id, db)
    return {
        "job_id": job_id,
        "status": job.status,
        "progress": job.progress,
        "log": job.log or [],
        "error_message": job.error_message,
    }


@router.get("/{job_id}/stream")
async def stream_calibration(job_id: str) -> StreamingResponse:
    """Server-sent events for a calibration job -- see crewsim.api.streaming."""
    return stream_job(job_id)
