def caveat_for(result: dict[str, Any]) -> str:
    """The corpus-specific caveat: the mock's, or the real extract's."""
    return REAL_DATA_CAVEAT if result.get("corpus_kind") == "REAL" else MOCK_DATA_CAVEAT


