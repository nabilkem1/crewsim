# sim ledger category -> D7 pay_code: the only categories with a real
# payroll counterpart at all. CANCELLATION/TERMINAL_PENALTY (the model's
# own uncovered-flight cost estimate) have no payroll line item -- a
# cancelled flight isn't paid to crew, so folding them into the headline
# gap would compare apples to oranges. Found while building this gate, not
# invented: verified via des.py's own ledger.book call sites (only 5
# category SHAPES are ever booked) against D7's own real pay_code values.
# DRAFT_TIER{n} (n=1..5, des.py's dynamic f"DRAFT_TIER{tier}") all map to
# the single D7 pay_code DRAFT_PREM -- D7 doesn't break draft premium out
# by impact tier, so neither does this comparison.
_RESERVE_PAY_CODE = {
    "RESERVE_STAFFING": "RESERVE_GTE",
    "RESERVE_UTILIZATION": "RESERVE_UTIL",
}


def _pay_code_for_sim_category(category: str) -> str | None:
    if category in _RESERVE_PAY_CODE:
        return _RESERVE_PAY_CODE[category]
    if category.startswith("DRAFT_TIER"):
        return "DRAFT_PREM"
    return None


def month_bounds(period: str) -> tuple[datetime.date, datetime.date]:
    """"YYYY-MM" -> (first day of month, first day of next month)."""
    year, month = (int(p) for p in period.split("-"))
    start = datetime.date(year, month, 1)
    end = datetime.date(year + 1, 1, 1) if month == 12 else datetime.date(year, month + 1, 1)
    return start, end


def _scope_crew_ids(cfg: config.BaseConfig) -> set[str]:
    d1 = loaders.load_dataset(cfg, "d1_crew_master")
    d1 = d1.filter(
        (pl.col("base") == cfg.scope.base)
        & (pl.col("fleet") == cfg.scope.fleet)
        & (pl.col("position") == cfg.scope.position)
    )
    return set(d1.get_column("crew_id"))


def compute_actual_cost(cfg: config.BaseConfig, period: str) -> dict[str, Any]:
    """Real D7/D10 rows for cfg.scope's crew, for this exact pay_period."""
    start, end = month_bounds(period)
    scope_ids = _scope_crew_ids(cfg)

    d7 = loaders.load_dataset(cfg, "d7_pay_register").filter(
        (pl.col("pay_period") == period) & (pl.col("crew_id").is_in(list(scope_ids)))
    )
    by_pay_code = dict(
        d7.group_by("pay_code").agg(pl.col("amount_cad").sum()).iter_rows()
    )

    d10 = loaders.load_dataset(cfg, "d10_positioning_invoices").filter(
        (pl.col("date") >= start) & (pl.col("date") < end) & (pl.col("crew_id").is_in(list(scope_ids)))
    )
    positioning_total = float(d10.get_column("amount_cad").sum()) if d10.height else 0.0

    comparable_codes = {"RESERVE_GTE", "RESERVE_UTIL", "DRAFT_PREM"}
    comparable = sum(by_pay_code.get(code, 0.0) for code in comparable_codes)
    comparable_rows = d7.filter(pl.col("pay_code").is_in(list(comparable_codes)))
    return {
        "by_pay_code": by_pay_code,
        "comparable_total": float(comparable),
        "positioning_total": positioning_total,
        "n_crew": len(scope_ids),
        "n_comparable_rows": comparable_rows.height,
        "n_crew_with_activity": comparable_rows.select("crew_id").n_unique(),
    }


def compute_simulated_cost(sim: Simulation) -> dict[str, Any]:
    by_category: dict[str, float] = {}
    for row in sim.ledger.rows:
        by_category[row.category] = by_category.get(row.category, 0.0) + row.amount

    comparable = sum(
        amount for category, amount in by_category.items() if _pay_code_for_sim_category(category) is not None
    )
    excluded = sum(
        amount for category, amount in by_category.items() if _pay_code_for_sim_category(category) is None
    )
    return {
        "by_category": by_category,
        "comparable_total": float(comparable),
        "excluded_total": float(excluded),
    }


def run_v6_gate(cfg: config.BaseConfig, costs: Any, policy: Policy, period: str) -> dict[str, Any]:
    start, end = month_bounds(period)
    sim = replay.run_historical_period(cfg, costs, policy, start, end, trace=False, verbose_trace=False)

    actual = compute_actual_cost(cfg, period)
    simulated = compute_simulated_cost(sim)

    gap = simulated["comparable_total"] - actual["comparable_total"]
    gap_pct = (gap / actual["comparable_total"] * 100.0) if actual["comparable_total"] else None

    return {
        "period": period,
        "policy_id": policy.policy_id,
        "actual": actual,
        "simulated": simulated,
        "gap": gap,
        "gap_pct": gap_pct,
    }


def print_v6_report(result: dict[str, Any]) -> None:
    print(MOCK_DATA_CAVEAT)
    print(f"\nGate V6 -- Cost Backtest, period {result['period']}, policy {result['policy_id']}")
    print("  Comparable categories (RESERVE_STAFFING/RESERVE_GTE, RESERVE_UTILIZATION/RESERVE_UTIL, "
          "DRAFT_TIER*/DRAFT_PREM):")
    print(f"    Actual (D7)     = ${result['actual']['comparable_total']:>14,.2f}  "
          f"({result['actual']['n_crew']} crew in scope, "
          f"{result['actual']['n_crew_with_activity']} with a comparable pay row, "
          f"{result['actual']['n_comparable_rows']} rows total -- D7 only records reserve/draft "
          f"EVENTS, not full payroll, so most crew having zero rows is expected, not a filter bug)")
    print(f"    Simulated       = ${result['simulated']['comparable_total']:>14,.2f}")
    print(f"    Gap             = ${result['gap']:>+14,.2f}", end="")
    if result["gap_pct"] is not None:
        print(f"  ({result['gap_pct']:+.1f}%)")
    else:
        print()

    print("\n  Excluded from the comparable gap (no counterpart on the other side):")
    print(f"    Simulated CANCELLATION/TERMINAL_PENALTY (no payroll line item) = "
          f"${result['simulated']['excluded_total']:,.2f}")
    print(f"    Actual D10 positioning/deadhead invoices (not modelled by the engine) = "
          f"${result['actual']['positioning_total']:,.2f}")

    print("\n  Bias decomposition (spec Sec9.2 -- qualitative, not computed):")
    for row in SPEC_BIAS_DECOMPOSITION:
        print(f"    {row['direction']:<11} {row['mechanism']}: {row['effect']}")

    print(f"\n{MOCK_DATA_CAVEAT}")
