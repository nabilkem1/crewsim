import datetime
import hashlib
import json
import os
import pathlib

import numpy as np
import polars as pl

from .. import config
from ..calibration import delays, nhpp
from ..engine import crn, roster_loader

# Bumped whenever the DRAW STRUCTURE changes (which streams exist, what each
# consumes), so pre-change caches can never be mistaken for post-change ones
# even under an identical parameter store. "g2" = the AUD-27 stream split
# (severity and sick counts each on their own named stream).
GENERATOR_EPOCH = "g2"


def _cache_signature(cfg: config.BaseConfig, season: str, master_seed: str, n_scenarios: int) -> str:
    """Every input that determines the generated bytes, in one key string.

    AUD-07: the key used to be (master_seed, n_scenarios, content_hash) only
    -- but generation also consumes cfg.scope (the GLM covariates), the
    horizon length (row count per scenario) and the roster template window
    (day-of-week anchoring). Changing any of those in base.yaml silently
    reused a stale cache, and missing days then read back as zero sick calls.
    """
    from ..engine import roster_loader

    params_dir = config.resolve(cfg, "params_dir")
    params_path = params_dir / f"params_v{_package_version()}_{season}.json"
    if not params_path.is_file():
        raise FileNotFoundError(f"Missing parameter store for {season}. Run calibration first.")
    content_hash = json.loads(params_path.read_text()).get("content_hash", "missing")
    window_start, _ = roster_loader.select_template_window(cfg)
    scope = cfg.scope
    return "|".join(
        [
            GENERATOR_EPOCH, master_seed, str(n_scenarios), content_hash,
            scope.base, scope.fleet, scope.position, season,
            str(cfg.horizon.horizon_days), window_start.isoformat(),
        ]
    )


def scenario_set_path(
    cfg: config.BaseConfig, season: str, master_seed: str, n_scenarios: int
) -> pathlib.Path:
    """Where this configuration's scenario set is cached.

    Public because more than one caller needs the file rather than the
    generate-or-skip return value: `generate_scenarios` answers "did I have to
    build it?" (None on a cache hit), which is useless to anyone who simply
    wants to read the rows. des.py delegates here (AUD-07) so there is exactly
    one cache-key computation in the codebase.
    """
    params_dir = config.resolve(cfg, "params_dir")
    cache_key = _cache_signature(cfg, season, master_seed, n_scenarios)
    h = hashlib.blake2b(cache_key.encode(), digest_size=16).hexdigest()
    return params_dir / "scenarios" / f"scenario_set_{h}.parquet"


def load_scenario_set(
    cfg: config.BaseConfig, season: str, master_seed: str, n_scenarios: int
) -> pl.DataFrame:
    """The generated scenario set as a DataFrame, building it if absent.

    Columns: scenario, day, regime, multiplier, sick_calls, delayed_flights,
    delay_minutes -- one row per scenario-day. This is the exogenous demand
    every policy is run against, so it is the same table for all of them;
    that is what makes it meaningful to show a scenario's shape once rather
    than per policy.

    delayed_flights/delay_minutes are AMBIENT flight delay (real D8-measured
    lateness for this base+fleet, independent of any reserve/draft decision)
    -- drawn from an independent CRN stream ("flight_delays") so their
    presence never perturbs the sick_calls sequence an existing scenario set
    already produced.
    """
    generate_scenarios(cfg, season, master_seed, n_scenarios)
    return pl.read_parquet(scenario_set_path(cfg, season, master_seed, n_scenarios))


def _package_version() -> str:
    import importlib.metadata

    try:
        return importlib.metadata.version("crewsim")
    except Exception:  # noqa: BLE001 - a version lookup must not abort generation
        return "unknown"


def generate_scenarios(cfg: config.BaseConfig, season: str, master_seed: str, n_scenarios: int) -> str | None:
    """
    Generates scenarios directly from frozen parameters.
    Returns None if cache hit, else path to generated parquet.
    """
    params_dir = config.resolve(cfg, "params_dir")
    import importlib.metadata
    try:
        version = importlib.metadata.version("crewsim")
    except Exception:  # noqa: BLE001 - a version lookup must not abort generation
        version = "unknown"
        
    params_path = params_dir / f"params_v{version}_{season}.json"
    if not params_path.is_file():
        raise FileNotFoundError(f"Missing parameter store for {season}. Run calibration first.")
        
    with open(params_path) as f:
        store = json.load(f)
        
    # Cache key: every generation input, via the single shared computation
    # (see _cache_signature -- n_scenarios matters because the parquet only
    # holds rows for the ids it was generated with, S1d-04d; scope/horizon/
    # template-window matter per AUD-07).
    scen_dir = params_dir / "scenarios"
    scen_dir.mkdir(exist_ok=True)
    out_file = scenario_set_path(cfg, season, master_seed, n_scenarios)

    if out_file.is_file():
        return None # Cache hit
        
    # Generate scenarios
    streams = crn.generate_streams(master_seed, n_scenarios)
    
    horizon_days = cfg.horizon.horizon_days
    
    # From store
    pi0 = store["markov_steady_state_pi0"]
    P = store["markov_transition_matrix_P"]
    multipliers = store["intensity_multipliers"]
    try:
        sick_nhpp = store["sick_call_nhpp"]
        sick_coefficients = sick_nhpp["coefficients"]
        sick_category_levels = sick_nhpp["category_levels"]
        sick_dispersion = sick_nhpp["dispersion"]
    except KeyError as e:
        raise KeyError(
            f"Parameter store {params_path} is missing {e} under sick_call_nhpp -- "
            "it was fitted before category_levels was added to the calibration "
            "pipeline. Re-run calibration to regenerate it."
        ) from e
    try:
        delay_mixture = store["flight_delay_mixture"]
        delay_by_regime = delay_mixture["delay_by_regime"]
        delay_components = delay_mixture["components"]
    except KeyError as e:
        raise KeyError(
            f"Parameter store {params_path} is missing {e} under flight_delay_mixture -- "
            "it was fitted before delay_by_regime was added to the calibration "
            "pipeline. Re-run calibration to regenerate it."
        ) from e

    states = ["CALM", "NORMAL", "DISRUPTED", "SEVERE"]

    # Build transition matrix array
    P_matrix = np.zeros((4, 4))
    for i, s1 in enumerate(states):
        for j, s2 in enumerate(states):
            P_matrix[i, j] = P[s1][s2]

    pi0_array = np.array([pi0[s] for s in states])

    # Real calendar anchor for this horizon, so day-of-week is the actual
    # day-of-week the NHPP was fit against -- not an arbitrary index. Uses
    # the same anchoring roster_loader.load_rosters() already uses for this
    # exact horizon (S1d-04b), so scenario days and roster days agree on
    # what calendar date "day 3" is.
    window_start, _window_end = roster_loader.select_template_window(cfg)

    rows = []

    for scen_idx, stream in enumerate(streams):
        # AUD-27 / §5.2: one named stream per stochastic source. Severity and
        # sick-call counts used to share a single "scenario_generation"
        # stream, so any structural change to one source's draws would have
        # silently shifted the other's whole sequence. GENERATOR_EPOCH ("g2")
        # in the cache key is what keeps pre-split caches from being reused.
        severity_rng = crn.event_rng(stream, "severity")
        sick_rng = crn.event_rng(stream, "sick_calls")
        delay_rng = crn.event_rng(stream, "flight_delays")

        current_state_idx = -1

        for day in range(horizon_days):
            if day == 0:
                # Use pi0 for day 1
                current_state_idx = severity_rng.choice(4, p=pi0_array)
            else:
                current_state_idx = severity_rng.choice(4, p=P_matrix[current_state_idx])

            current_state = states[current_state_idx]
            mult = multipliers[current_state]

            # Real fitted intensity for this scope on this calendar day, not
            # a fabricated constant re-scaled by a regime multiplier: the
            # NHPP GLM already has its own C(regime) coefficient, fit with
            # proper adjustment for season/day-of-week/base/fleet/position,
            # so re-multiplying by `mult` here would double-count the same
            # regime effect through two different, uncoordinated channels.
            # `mult` is still recorded on each row below as calibrated
            # metadata -- it is simply not an input to sick_calls anymore.
            calendar_date = window_start + datetime.timedelta(days=day)
            covariates = {
                "season": season,
                "day_of_week": str(calendar_date.isoweekday()),
                "base": cfg.scope.base,
                "fleet": cfg.scope.fleet,
                "position": cfg.scope.position,
                "regime": current_state,
            }
            mean_sick_calls = nhpp.predict_intensity(sick_coefficients, sick_category_levels, covariates)
            sick_calls = nhpp.sample_count(sick_rng, mean_sick_calls, sick_dispersion)

            # Ambient flight delay for this regime day: a real measured
            # flights/day count for this base+fleet (rounded -- flight
            # schedules are fixed by day/season, not themselves a random
            # draw; only whether each one is delayed is), each flight
            # independently delayed at this regime's real fitted
            # probability. Same "fit per regime, don't scale by `mult`
            # after" rule as sick_calls above (see fit_delays' own note).
            regime_delay = delay_by_regime[current_state]
            n_flights = round(regime_delay["mean_flights_per_day"])
            delayed_flights = (
                int(delay_rng.binomial(n_flights, regime_delay["delay_probability"]))
                if n_flights > 0
                else 0
            )
            delay_minutes = sum(
                delays.sample_delay_minutes(delay_rng, delay_components) for _ in range(delayed_flights)
            )

            rows.append({
                "scenario": scen_idx,
                "day": day,
                "regime": current_state,
                "multiplier": mult,
                "sick_calls": sick_calls,
                "delayed_flights": delayed_flights,
                "delay_minutes": delay_minutes,
            })

    df = pl.DataFrame(rows)
    # Write-then-rename, not a direct write to out_file: the grid runner
    # (S1e-04) runs several policies as separate OS processes via joblib, and
    # each one independently misses the is_file() cache check above the
    # first time a given (master_seed, n_scenarios) pair is uncached -- a
    # direct write lets one process's partial parquet bytes be read by
    # another mid-write (polars.exceptions.ComputeError: "File out of
    # specification"), found via S1e-04's own real 1000-scenario, 5-policy
    # manual check. os.replace is atomic on the same filesystem, so a reader
    # always sees either the fully-old state (file absent) or the
    # fully-new one, never a partial write. Content is a pure function of
    # (master_seed, n_scenarios, content_hash), so two processes racing to
    # both generate and rename is wasted duplicate work, not a correctness
    # issue -- whichever rename lands last still produces identical bytes.
    tmp_file = out_file.with_name(f"{out_file.name}.tmp.{os.getpid()}")
    df.write_parquet(tmp_file)
    os.replace(tmp_file, out_file)

    return str(out_file)
