DECLARE @BEGIN AS DATE;
DECLARE @END AS DATE;
SET @BEGIN = '2026-01-01';
SET @END = '2026-01-31';

;WITH RO AS
(
SELECT CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) AS LEG_DATE,
	   POS, ID, DUTYDAY, DUTYNO,LEG_DAY, LEG_CARRIER, LEG_DEP, LEG_FLT,LEG_LEGCD, GRDDUTYBEG FROM TSC.DBO.ROSTER
WHERE CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) >= @BEGIN AND CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) <= @END
),
RDT1 AS 
(
SELECT CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) AS LEG_DATE,
	   * FROM TSC.DBO.ROSTERDT
WHERE CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) >= @BEGIN AND CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) <= @END
AND LEG_FLT != 0
),
RDT2 AS 
(
SELECT CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) AS LEG_DATE,
	   * FROM TSC.DBO.ROSTERDT
WHERE CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) >= @BEGIN AND CAST(DATEADD(DAY,LEG_DAY,'1980-01-01') AS DATE) <= @END
AND LEG_FLT = 0
), 
RF_1 AS
(
SELECT RO.LEG_DATE, RO.ID, RO.POS, RO.DUTYDAY, RO.DUTYNO, RO.LEG_DAY, RO.LEG_CARRIER, RO.LEG_FLT, RO.LEG_LEGCD, 
RDT1.RECTYPE, RDT1.VALUE1, RDT1.VALUE2
FROM RO
LEFT JOIN RDT1 ON RO.ID = RDT1.ID 
				  AND RO.LEG_DAY = RDT1.LEG_DAY
				  AND RO.LEG_DEP = RDT1.LEG_DEP
				  AND RO.LEG_CARRIER = RDT1.LEG_CARRIER
				  AND RO.LEG_FLT = RDT1.LEG_FLT
				  AND RO.LEG_LEGCD = RDT1.LEG_LEGCD
), 
RF_2 AS
(
SELECT RO.LEG_DATE, RO.ID, RO.POS, RO.DUTYDAY, RO.DUTYNO, RO.LEG_DAY, RO.LEG_CARRIER, RO.LEG_FLT, RO.LEG_LEGCD, 
RDT2.RECTYPE, RDT2.VALUE1, RDT2.VALUE2
FROM RO
LEFT JOIN RDT2 ON RO.ID = RDT2.ID 
				  AND RO.LEG_DAY = RDT2.LEG_DAY
),
RF AS
(
SELECT * FROM RF_1
UNION ALL
SELECT * FROM RF_2
)

SELECT *
, CASE WHEN VALUE1 = 15 THEN 'PNC DRAFT A LA BASE'
	   WHEN VALUE1 = 16 THEN 'PNC DRAFT OUT OF BASE/HORS BASE'
	   WHEN VALUE1 = 19 THEN 'DRAFT PILOTE'
	   WHEN VALUE1 = 20 THEN 'DRAFT PILOTE SUR VACANCES'
  ELSE ''
END AS DRAFT_TYPE
	   
FROM RF
WHERE --ID = 2758 AND 
RECTYPE = 21 AND VALUE1 IN (15,16,19,20)
ORDER BY ID, LEG_DATE