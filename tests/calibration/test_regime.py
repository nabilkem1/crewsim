def test_exposure_counts_distinct_crew_on_duty_with_exclusive_end(monkeypatch: pytest.MonkeyPatch) -> None:
    cfg = config.load()
    t = datetime.datetime

    d2 = pl.DataFrame({
        "crew_id": ["A", "B", "B", "C"],
        "base": ["YUL"] * 4,
        "block_type": ["PAIRING", "RESERVE", "PAIRING", "DAY_OFF"],
        "start_local": [t(2024, 1, 1, 6), t(2024, 1, 2, 0), t(2024, 1, 2, 12), t(2024, 1, 1)],
        "end_local": [t(2024, 1, 3, 0), t(2024, 1, 3, 0), t(2024, 1, 2, 20), t(2024, 1, 5)],
    })
    empty_d4 = pl.DataFrame({"absence_start": [], "base": []}, schema={"absence_start": pl.Date, "base": pl.String})
    empty_d8 = pl.DataFrame(
        {"date": [], "origin": [], "delay_minutes": [], "cancelled": []},
        schema={"date": pl.Date, "origin": pl.String, "delay_minutes": pl.Int64, "cancelled": pl.Int64},
    )
    data = {"d2_rosters": d2, "d4_absences": empty_d4, "d8_flight_movements": empty_d8}
    monkeypatch.setattr(regime.loaders, "load_dataset", lambda cfg, name: data[name])

    ex = regime.load_inputs(cfg).exposure.sort("date")
    by_day = dict(zip(ex["date"].to_list(), ex["exposure"].to_list(), strict=True))
    assert by_day == {datetime.date(2024, 1, 1): 1.0, datetime.date(2024, 1, 2): 2.0}, (
        "A covers Jan 1-2 (ends 00:00 on the 3rd), B counts once on Jan 2, DAY_OFF never counts"
    )


# ============================================== the packaged mock corpus

def test_hmm_recovers_the_mock_generators_hidden_regime() -> None:
    """The mock corpus generator draws a hidden regime first and produces
    D4/D8 from it; its D9 file holds that truth. The old chaos-quantile
    labelling agreed with it on 25.8% of days. The HMM -- which never reads
    D9 -- must do far better."""
    cfg = config.load()
    w = cfg.windows.get("fitting")
    window = (w.start, w.end)
    labels = regime.label_station_days(cfg, window, stations=[cfg.scope.base], seasons=["winter_sun"])
    res = regime.label_agreement(cfg, "winter_sun", window, labels=labels)
    assert res["n_days"] > 250
    assert res["agreement_rate"] > 0.7, res
