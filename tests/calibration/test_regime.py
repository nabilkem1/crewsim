"""Severity regime as a hidden Markov model (S0-06, rewritten by F-42 Option B).

What these tests pin down:
  * the emission model treats a day with no data as uninformative;
  * EM recovers a KNOWN regime process (transition matrix, emissions, labels)
    from synthetic data generated by that process;
  * states come out ordered CALM -> SEVERE, the fit is reproducible, and no
    transition row is ever absorbing;
  * fit_regime runs end to end WITHOUT D9 -- it is never even loaded;
  * on the packaged mock corpus, whose D9 holds the generator's true hidden
    regime, the HMM recovers that regime far better than the old quantile
    labelling did (25.8% agreement).
"""
from __future__ import annotations

import datetime
from typing import Any

import numpy as np
import polars as pl
import pytest

from crewsim import config
from crewsim.calibration import hmm, regime

TRUE_P = np.array([
    [0.80, 0.15, 0.04, 0.01],
    [0.10, 0.78, 0.10, 0.02],
    [0.03, 0.15, 0.72, 0.10],
    [0.01, 0.05, 0.24, 0.70],
])
TRUE_Q = np.array([0.04, 0.12, 0.25, 0.42])       # P(delayed)
TRUE_R = np.array([0.002, 0.004, 0.02, 0.06])     # P(cancelled)
TRUE_LAM = np.array([0.005, 0.012, 0.025, 0.045])  # sick calls per crew on duty
FLIGHTS, EXPOSURE = 40, 150


def _simulate(n_days: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    """Days generated by the TRUE process: (X in hmm.OBS_COLUMNS order, states)."""
    rng = np.random.default_rng(seed)
    states = np.empty(n_days, dtype=int)
    states[0] = 1
    for t in range(1, n_days):
        states[t] = rng.choice(4, p=TRUE_P[states[t - 1]])
    X = np.zeros((n_days, len(hmm.OBS_COLUMNS)))
    for t, k in enumerate(states):
        _, nd, nc = rng.multinomial(FLIGHTS, [1 - TRUE_Q[k] - TRUE_R[k], TRUE_Q[k], TRUE_R[k]])
        X[t] = [FLIGHTS, nd, nc, rng.poisson(EXPOSURE * TRUE_LAM[k]), EXPOSURE]
    return X, states


def _fit(X: np.ndarray, lengths: list[int], seed: int = 1) -> tuple[hmm.DisruptionHMM, dict[str, Any]]:
    return hmm.fit_best(
        X, lengths, 4,
        seed_sequence=np.random.SeedSequence(seed),
        n_restarts=4, max_iter=300, tol=1e-4,
        init_self_transition=0.7, transition_pseudocount=0.5, min_probability=1e-6,
        quantile_seed=[0.5, 0.8, 0.95], restart_agreement_tol=1e-4,
    )


# ======================================================== emission model

def test_a_day_without_data_is_uninformative() -> None:
    """n_flights = 0 and exposure = 0 -> log-likelihood exactly 0 in every
    state: a missing day neither looks calm nor severe."""
    X = np.zeros((1, len(hmm.OBS_COLUMNS)))
    ll = hmm.emission_log_likelihood(X, TRUE_Q, TRUE_R, TRUE_LAM, 1e-6)
    assert np.allclose(ll, 0.0)


def test_emissions_prefer_the_state_that_produced_the_day() -> None:
    severe_day = np.array([[40, 17, 3, 7, 150]], dtype=float)
    calm_day = np.array([[40, 1, 0, 0, 150]], dtype=float)
    assert np.argmax(hmm.emission_log_likelihood(severe_day, TRUE_Q, TRUE_R, TRUE_LAM, 1e-6)) == 3
    assert np.argmax(hmm.emission_log_likelihood(calm_day, TRUE_Q, TRUE_R, TRUE_LAM, 1e-6)) == 0


# ============================================================ EM recovery

@pytest.fixture(scope="module")
def synthetic_fit() -> tuple[hmm.DisruptionHMM, dict[str, Any], np.ndarray, np.ndarray, list[int]]:
    parts = [_simulate(150, seed) for seed in (11, 12, 13)]
    X = np.vstack([p[0] for p in parts])
    truth = np.concatenate([p[1] for p in parts])
    lengths = [150, 150, 150]
    model, report = _fit(X, lengths)
    return model, report, X, truth, lengths


def test_em_recovers_the_true_emissions(synthetic_fit: Any) -> None:
    model, *_ = synthetic_fit
    assert np.allclose(model.delay_prob_, TRUE_Q, atol=0.03)
    assert np.allclose(model.cancel_prob_, TRUE_R, atol=0.015)
    assert np.allclose(model.sick_rate_, TRUE_LAM, rtol=0.3)


def test_em_recovers_the_persistence_of_the_true_chain(synthetic_fit: Any) -> None:
    """450 days pin the diagonal (how long a regime lasts) to within ~0.2 --
    and, the property that makes bad WEEKS, every state is stickier than any
    single move out of it, as in the true chain."""
    model, *_ = synthetic_fit
    P = model.transmat_
    assert np.allclose(P.sum(axis=1), 1.0)
    assert np.allclose(np.diag(P), np.diag(TRUE_P), atol=0.2)
    assert all(np.argmax(P[k]) == k for k in range(4))


def test_viterbi_labels_recover_the_hidden_days(synthetic_fit: Any) -> None:
    model, _, X, truth, lengths = synthetic_fit
    path = model.predict(X, lengths)
    assert (path == truth).mean() > 0.85


def test_states_are_ordered_calm_to_severe(synthetic_fit: Any) -> None:
    model, *_ = synthetic_fit
    assert np.all(np.diff(model.delay_prob_) > 0)
    assert np.all(np.diff(model.sick_rate_) > 0)


def test_fit_report_is_honest(synthetic_fit: Any) -> None:
    _, report, X, _, lengths = synthetic_fit
    assert report["n_days"] == X.shape[0]
    assert report["n_sequences"] == len(lengths)
    assert report["converged"] is True
    assert 1 <= report["restarts_reaching_best"] <= report["restarts"]
    assert report["bic"] > -2 * report["log_likelihood"]


def test_fit_is_reproducible() -> None:
    X, _ = _simulate(200, 5)
    a, _ = _fit(X, [200], seed=3)
    b, _ = _fit(X, [200], seed=3)
    assert np.array_equal(a.transmat_, b.transmat_)
    assert np.array_equal(a.sick_rate_, b.sick_rate_)


def test_no_transition_row_is_absorbing_even_for_a_rare_state() -> None:
    """REVIEW-2 / AUD-18, restated for the HMM: a state seen on very few days
    must not become absorbing. The Dirichlet pseudo-count guarantees it."""
    X, _ = _simulate(120, 21)
    X[-1] = [FLIGHTS, 30, 8, 20, EXPOSURE]          # one extreme day at the very end
    model, _ = _fit(X, [120])
    assert np.all(np.diag(model.transmat_) < 1.0)
    assert np.all(model.transmat_ > 0.0)


def test_a_model_needs_at_least_two_days() -> None:
    with pytest.raises(ValueError, match="at least two days"):
        _fit(np.zeros((1, len(hmm.OBS_COLUMNS))), [1])


# ===================================================== pipeline plumbing

def _constant_exposure_cfg() -> config.BaseConfig:
    cfg = config.load()
    hmm_cfg = cfg.calibration.regime_hmm.model_copy(
        update={"sick_call_exposure": "constant", "n_restarts": 3, "candidate_n_states": [1, 4]}
    )
    cal = cfg.calibration.model_copy(update={"regime_hmm": hmm_cfg})
    return cfg.model_copy(update={"calibration": cal})


def _fake_corpus(cfg: config.BaseConfig, n_days: int = 500) -> dict[str, pl.DataFrame]:
    """D1/D4/D8 for the scoped base, generated by the TRUE process. No D9."""
    base, start = cfg.scope.base, datetime.date(2023, 12, 1)
    X, states = _simulate(n_days, 7)
    days = [start + datetime.timedelta(days=i) for i in range(n_days)]
    flights: dict[str, list[Any]] = {"date": [], "origin": [], "delay_minutes": [], "cancelled": []}
    absences: dict[str, list[Any]] = {"absence_start": [], "base": []}
    for d, row in zip(days, X, strict=True):
        n, nd, nc, s = (int(v) for v in row[:4])
        for i in range(n):
            flights["date"].append(d)
            flights["origin"].append(base)
            flights["delay_minutes"].append(60 if i < nd else 0)
            flights["cancelled"].append(1 if nd <= i < nd + nc else 0)
        absences["absence_start"].extend([d] * s)
        absences["base"].extend([base] * s)
    return {
        "d1_crew_master": pl.DataFrame({
            "crew_id": ["P1"], "base": [base], "crew_group": ["PILOT"], "employment_status": ["ACTIVE"],
        }),
        "d4_absences": pl.DataFrame(absences),
        "d8_flight_movements": pl.DataFrame(flights),
        "_states": pl.DataFrame({"date": days, "state": [regime.STATES[k] for k in states]}),
    }


@pytest.fixture
def no_d9_corpus(monkeypatch: pytest.MonkeyPatch, tmp_path: Any) -> tuple[config.BaseConfig, dict[str, pl.DataFrame]]:
    cfg = _constant_exposure_cfg()
    corpus = _fake_corpus(cfg)

    def load(_cfg: Any, name: str) -> pl.DataFrame:
        if name == "d9_station_days":
            raise AssertionError("D9 must not be read by the regime calibration (F-42)")
        return corpus[name]

    monkeypatch.setattr(regime.loaders, "load_dataset", load)
    monkeypatch.setattr(regime.config, "ensure_dir", lambda cfg, key: tmp_path)
    return cfg, corpus


def test_fit_regime_runs_without_d9(no_d9_corpus: Any) -> None:
    cfg, _ = no_d9_corpus
    res = regime.fit_regime(cfg, "winter_sun")

    assert res["method"] == "hidden_markov_model"
    assert res["station"] == cfg.scope.base
    assert set(res["matrix"]) == set(regime.STATES)
    for row in res["matrix"].values():
        assert abs(sum(row.values()) - 1.0) < 1e-9
        assert all(p > 0 for p in row.values())
    assert abs(sum(res["pi0"].values()) - 1.0) < 1e-9
    assert res["multipliers"]["NORMAL"] == pytest.approx(1.0)
    em = res["emissions"]
    assert [em[s]["delay_probability"] for s in regime.STATES] == sorted(
        em[s]["delay_probability"] for s in regime.STATES
    )
    assert res["model_selection"]["bic_preferred_n_states"] == 4, "4 regimes beat 1 on regime data"
    assert res["_saved_path"].endswith(".json")


def test_computed_labels_replace_d9(no_d9_corpus: Any) -> None:
    cfg, corpus = no_d9_corpus
    labels = regime.label_station_days(cfg, None, seasons=["winter_sun"])
    assert {"station", "date", "season", "disruption_class", "p_SEVERE"} <= set(labels.columns)
    assert set(labels["disruption_class"].unique()) <= set(regime.STATES)
    post = labels.select([pl.col(f"p_{s}") for s in regime.STATES]).to_numpy()
    assert np.allclose(post.sum(axis=1), 1.0)

    truth = corpus["_states"]
    joined = labels.join(truth, on="date", how="inner")
    accuracy = (joined["disruption_class"] == joined["state"]).mean()
    assert accuracy > 0.8, f"computed labels should recover the true hidden regime, got {accuracy:.0%}"


